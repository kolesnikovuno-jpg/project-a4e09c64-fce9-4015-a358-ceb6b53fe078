export const makeSketchPrompt = (brief: DesignBrief, locale: Locale): string => {
  const copy = designCopy[locale];
  const parts = [copy.promptIntro];
  if (brief.concept.trim()) parts.push(copy.promptConcept + ":\n" + brief.concept.trim());
  if (brief.purpose.trim()) parts.push(copy.promptPurpose + ":\n" + brief.purpose.trim());
  if (brief.character.trim()) parts.push(copy.promptCharacter + ":\n" + brief.character.trim());
  if (brief.constraints.trim()) parts.push(copy.promptConstraints + ":\n" + brief.constraints.trim());
  parts.push(copy.promptEnd);
  return parts.join("\n\n");
};
