export const eggUi:Record<Locale,EggUiCopy>={ru,uk,en};
export const getEggUi=(locale:Locale):EggUiCopy=>eggUi[locale];

// Directly rendering a workspace in tests/embedded UIs keeps the existing
// Russian copy. App routes set the locale through the shared EGG shell.
const EggUiLocaleContext=createContext<Locale>("ru");
export function EggUiProvider({locale,children}:{locale:Locale;children:ReactNode}){
 return <EggUiLocaleContext.Provider value={locale}>{children}</EggUiLocaleContext.Provider>;
}
export function useEggUi(){
 const locale=useContext(EggUiLocaleContext);
 return {locale,ui:eggUi[locale]};
}
